use crate::domain::media::ContainerFormat;
use serde::{Deserialize, Serialize};

/// First-class supported subtitle languages in `mvd`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TargetSubtitleLang {
    English,
    Indonesian,
}

impl TargetSubtitleLang {
    #[must_use]
    pub const fn iso_639_1(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Indonesian => "id",
        }
    }

    #[must_use]
    pub const fn iso_639_2_mkv(self) -> &'static str {
        match self {
            Self::English => "eng",
            Self::Indonesian => "ind",
        }
    }

    #[must_use]
    pub const fn display_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Indonesian => "Indonesian",
        }
    }
}

/// Distinguishes human-curated manual captions from automatic ASR/translated captions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SubtitleOrigin {
    Manual,
    AutoGeneratedAsr,
}

impl SubtitleOrigin {
    #[must_use]
    pub const fn badge(self) -> &'static str {
        match self {
            Self::Manual => "MANUAL",
            Self::AutoGeneratedAsr => "AUTO-ASR",
        }
    }
}

/// Resolved subtitle track to be acquired and processed for a specific language.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ResolvedSubtitleTrack {
    pub language: TargetSubtitleLang,
    pub raw_lang_key: String,
    pub origin: SubtitleOrigin,
    pub default_track: bool,
}

/// Defines how subtitles are stored when the container is `.mkv` vs `.mp4`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SubtitleDeliveryMode {
    /// Default for `.mkv`: Embeds `.srt` / `.ass` inside the Matroska container with `eng`/`ind` tags and removes sidecars.
    MkvInternalMux,
    /// Default for `.mp4`: Saves external sidecar `Title.en.srt` & `Title.id.srt` next to the `.mp4` AND embeds `mov_text` soft-subs.
    Mp4ExternalSidecarAndMovText,
    /// Alternative for `.mp4`: Writes only external `Title.en.srt` & `Title.id.srt` sidecar files without modifying the `.mp4`.
    ExternalSidecarSrtOnly,
    /// Subtitles disabled.
    Disabled,
}

impl SubtitleDeliveryMode {
    #[must_use]
    pub const fn default_for_container(container: ContainerFormat, enabled: bool) -> Self {
        if !enabled {
            return Self::Disabled;
        }
        match container {
            ContainerFormat::Mkv => Self::MkvInternalMux,
            ContainerFormat::Mp4 => Self::Mp4ExternalSidecarAndMovText,
            ContainerFormat::Webm => Self::ExternalSidecarSrtOnly,
            _ => Self::Disabled,
        }
    }

    #[must_use]
    pub const fn writes_external_sidecar(self) -> bool {
        matches!(
            self,
            Self::Mp4ExternalSidecarAndMovText | Self::ExternalSidecarSrtOnly
        )
    }
}

/// Resolves the optimal `EN` and `ID` subtitle plan from `yt-dlp`'s `subtitles` (manual)
/// and `automatic_captions` (ASR) keys without downloading duplicate manual+auto tracks.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SubtitleResolutionPlan {
    pub tracks: Vec<ResolvedSubtitleTrack>,
    pub delivery_mode: SubtitleDeliveryMode,
}

impl SubtitleResolutionPlan {
    #[must_use]
    pub fn resolve(
        manual_keys: &[String],
        auto_keys: &[String],
        want_en: bool,
        want_id: bool,
        allow_auto_fallback: bool,
        container: ContainerFormat,
    ) -> Self {
        let mut tracks = Vec::new();

        if want_en {
            if let Some(track) = Self::pick_for_lang(
                TargetSubtitleLang::English,
                &["en", "en-US", "en-GB", "en-orig"],
                manual_keys,
                auto_keys,
                allow_auto_fallback,
                true,
            ) {
                tracks.push(track);
            }
        }

        if want_id {
            let is_default = tracks.is_empty();
            if let Some(track) = Self::pick_for_lang(
                TargetSubtitleLang::Indonesian,
                &["id", "id-ID", "id-orig", "ind"],
                manual_keys,
                auto_keys,
                allow_auto_fallback,
                is_default,
            ) {
                tracks.push(track);
            }
        }

        let delivery_mode =
            SubtitleDeliveryMode::default_for_container(container, !tracks.is_empty());

        Self {
            tracks,
            delivery_mode,
        }
    }

    fn pick_for_lang(
        language: TargetSubtitleLang,
        candidates: &[&str],
        manual_keys: &[String],
        auto_keys: &[String],
        allow_auto_fallback: bool,
        default_track: bool,
    ) -> Option<ResolvedSubtitleTrack> {
        for &cand in candidates {
            if let Some(found) = manual_keys.iter().find(|k| k.as_str() == cand) {
                return Some(ResolvedSubtitleTrack {
                    language,
                    raw_lang_key: found.clone(),
                    origin: SubtitleOrigin::Manual,
                    default_track,
                });
            }
        }
        let prefix = language.iso_639_1();
        if let Some(found) = manual_keys.iter().find(|k| k.starts_with(prefix)) {
            return Some(ResolvedSubtitleTrack {
                language,
                raw_lang_key: found.clone(),
                origin: SubtitleOrigin::Manual,
                default_track,
            });
        }

        if !allow_auto_fallback {
            return None;
        }

        for &cand in candidates {
            if let Some(found) = auto_keys.iter().find(|k| k.as_str() == cand) {
                return Some(ResolvedSubtitleTrack {
                    language,
                    raw_lang_key: found.clone(),
                    origin: SubtitleOrigin::AutoGeneratedAsr,
                    default_track,
                });
            }
        }
        if let Some(found) = auto_keys.iter().find(|k| k.starts_with(prefix)) {
            return Some(ResolvedSubtitleTrack {
                language,
                raw_lang_key: found.clone(),
                origin: SubtitleOrigin::AutoGeneratedAsr,
                default_track,
            });
        }

        None
    }
}
