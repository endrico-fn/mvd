#[test]
fn test_t02_manual_en_and_auto_id_subtitle_deduplication_and_mp4_sidecar() {
    // From live test T-02 (SPwyp2NG-bE): 'en' is in manual_subtitles, while 'id' is only in automatic_captions
    let manual = vec!["en".to_string()];
    let auto = vec!["en".to_string(), "en-orig".to_string(), "id".to_string()];

    // 1. MKV Mode: Internal mux
    let mkv_plan =
        SubtitleResolutionPlan::resolve(&manual, &auto, true, true, true, ContainerFormat::Mkv);
    assert_eq!(mkv_plan.tracks.len(), 2);
    assert_eq!(mkv_plan.tracks[0].origin, SubtitleOrigin::Manual);
    assert_eq!(mkv_plan.tracks[1].origin, SubtitleOrigin::AutoGeneratedAsr);
    assert_eq!(mkv_plan.delivery_mode, SubtitleDeliveryMode::MkvInternalMux);

    // 2. MP4 Mode: External Sidecar .srt + mov_text soft-embed
    let mp4_plan =
        SubtitleResolutionPlan::resolve(&manual, &auto, true, true, true, ContainerFormat::Mp4);
    assert_eq!(
        mp4_plan.delivery_mode,
        SubtitleDeliveryMode::Mp4ExternalSidecarAndMovText
    );

    let meta = mvd::domain::metadata::EditableMetadata::default_for_title("BASH Scripting EP 1");
    let mux = FfmpegCommandBuilder::build_video_mux_plan(
        Path::new("/tmp/video.mp4"),
        Some(Path::new("/tmp/audio.m4a")),
        &[
            (0, PathBuf::from("/tmp/sub.en.srt")),
            (1, PathBuf::from("/tmp/sub.id.srt")),
        ],
        None,
        &meta,
        &mp4_plan,
        ContainerFormat::Mp4,
        Path::new("/home/porvata/Downloads/mvd"),
        "BASH Scripting EP 1 [SPwyp2NG-bE]",
    );
    assert_eq!(mux.external_sidecar_subs.len(), 2);
    assert!(mux.external_sidecar_subs[0]
        .to_string_lossy()
        .ends_with(".en.srt"));
    assert!(mux.external_sidecar_subs[1]
        .to_string_lossy()
        .ends_with(".id.srt"));
}

#[test]
fn test_t05_art_track_1x1_vs_t04_vevo_16x9_as_is_thumbnail_selection() {
    // T-05 (5xx9gTEQaiQ): Art Track has 544x544 square cover (pref -39) and pillarboxed 1280x720 hq720.jpg (pref -3)
    let thumbs = vec![
        YtDlpThumbnailJson {
            id: Some("2".to_string()),
            url: "https://yt3.googleusercontent.com/cover=w544-h544".to_string(),
            width: Some(544),
            height: Some(544),
            preference: Some(-39),
        },
        YtDlpThumbnailJson {
            id: Some("37".to_string()),
            url: "https://i.ytimg.com/vi/5xx9gTEQaiQ/hq720.jpg".to_string(),
            width: Some(1280),
            height: Some(720),
            preference: Some(-3),
        },
    ];

    let art_picked = SmartThumbnailSelector::select_best(&thumbs, true, false).unwrap();
    assert_eq!(art_picked.aspect_kind, AspectRatioKind::Square1x1);
    assert_eq!(art_picked.width, 544);

    // VEVO Music Video (is_vevo_or_landscape_mv = true): keeps 16:9 as-is!
    let vevo_picked = SmartThumbnailSelector::select_best(&thumbs, false, true).unwrap();
    assert_eq!(vevo_picked.aspect_kind, AspectRatioKind::Landscape16x9);
    assert_eq!(vevo_picked.width, 1280);
}

#[test]
fn test_t07_spotify_duration_scored_bridge_avoids_double_vevo_video() {
    let sp = SpotifyTrackMetadata {
        spotify_id: "7MtVPRGtZl6rPjMfLoI3Lh".to_string(),
        title: "Fuck it I love you".to_string(),
        artists: vec!["Lana Del Rey".to_string()],
        duration_ms: 218_287,
        release_date: Some("2019-08-30".to_string()),
        cover_art_640_url: None,
    };

    let candidates = vec![
        YtSearchAudioCandidate {
            video_id: "LrSX_OcpeJg".to_string(),
            title: "Lana Del Rey - Fuck it I love you / The greatest".to_string(),
            channel: "Lana Del Rey".to_string(),
            duration_secs: 560,
        },
        YtSearchAudioCandidate {
            video_id: "wDWE_Qp3oKM".to_string(),
            title: "Lana Del Rey - Fuck it I love you".to_string(),
            channel: "Tristan Music".to_string(),
            duration_secs: 219,
        },
    ];

    let best = SpotifyBridge::pick_best_audio_match(&sp, &candidates).unwrap();
    assert_eq!(best.video_id, "wDWE_Qp3oKM");
}
